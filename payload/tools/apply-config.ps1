function Get-KeyValues($lines) {
    $kv = @{}
    foreach ($l in $lines) { if ($l -match '^\s*([A-Za-z][\w.\-]*)\s*=\s*(.*?)\s*$' -and -not $kv.ContainsKey($Matches[1])) { $kv[$Matches[1]] = $Matches[2] } }
    $kv
}

