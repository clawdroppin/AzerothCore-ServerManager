function Test-EventActive($e, [datetime]$now) {
    # Day -1 = every day; 0..6 = Sunday..Saturday. Times are HH:mm. A window may wrap past midnight / the weekend.
    $toMin = { param($t) $p = "$t" -split ':'; [int]$p[0] * 60 + [int]$p[1] }
    $s = & $toMin $e.StartTime; $f = & $toMin $e.EndTime
    if ([int]$e.StartDay -lt 0) { $n = $now.Hour * 60 + $now.Minute }
    else { $n = [int]$now.DayOfWeek * 1440 + $now.Hour * 60 + $now.Minute; $s += [int]$e.StartDay * 1440; $f += [int]$e.EndDay * 1440 }
    if ($s -le $f) { $s -le $n -and $n -lt $f } else { $n -ge $s -or $n -lt $f }
}
$EventMult = @{}; $ActiveEvents = @()
foreach ($e in @($S.Events)) {
    if (-not $e -or -not $e.Enabled -or -not $EventKeys[$e.Kind]) { continue }
    if (Test-EventActive $e (Get-Date)) {
        $ActiveEvents += $e.Name
        foreach ($k in $EventKeys[$e.Kind]) { $EventMult[$k] = $(if ($EventMult[$k]) { $EventMult[$k] } else { 1.0 }) * [double]$e.Multiplier }
    }
}

function Set-Conf([string]$file, [hashtable]$values, [string]$Template) {
    $dist = if ($Template -and (Test-Path $Template)) { $Template } else { "$file.dist" }
    if (-not (Test-Path $dist)) { Write-Host "skip $(Split-Path $file -Leaf) (module not installed)"; return }
    $rel = $file.Substring($Configs.Length + 1).Replace('\', '/').ToLower()
    $lines = [System.Collections.Generic.List[string]](Get-Content $dist)

    # A .conf this app has not generated yet (older install, or a server added with "Add existing folder")
    # may contain hand-made changes: keep them, as overrides the user can see and undo in "All options".
    if ((Test-Path $file) -and (Get-Content $file -TotalCount 1) -ne $Marker) {
        $distVals = Get-KeyValues $lines
        $cur = Get-KeyValues (Get-Content $file)
        foreach ($k in $cur.Keys) {
            if ($values.ContainsKey($k) -or $k -match $ConditionalKeys) { continue }
            if ($distVals.ContainsKey($k) -and $distVals[$k].Trim('"') -eq $cur[$k].Trim('"')) { continue }
            if (-not $Overrides[$rel]) { $Overrides[$rel] = @{} }
            if (-not $Overrides[$rel].ContainsKey($k)) { $Overrides[$rel][$k] = $cur[$k]; $script:CapturedOverrides++ }
        }
    }

    $all = $values.Clone()
    if ($Overrides[$rel]) { foreach ($k in $Overrides[$rel].Keys) { $all[$k] = $Overrides[$rel][$k] } }
    if ($rel -eq 'worldserver.conf' -and $EventMult.Count) {
        $distVals = Get-KeyValues $lines
        foreach ($k in $EventMult.Keys) {
            $base = 1.0
            $raw = if ($all.ContainsKey($k)) { $all[$k] } else { $distVals[$k] }
            [void][double]::TryParse("$raw", [Globalization.NumberStyles]::Float, $Inv, [ref]$base)
            $all[$k] = ($base * $EventMult[$k]).ToString('0.###', $Inv)
        }
    }
    foreach ($key in $all.Keys) {
        $pattern = '^\s*' + [regex]::Escape($key) + '\s*='
        $idx = -1
        for ($i = 0; $i -lt $lines.Count; $i++) { if ($lines[$i] -imatch $pattern) { $idx = $i; break } }
        if ($idx -ge 0) { $lines[$idx] = (($lines[$idx] -split '=', 2)[0].Trim()) + ' = ' + $all[$key] }
        else { $lines.Add("$key = $($all[$key])") }
    }
    $lines.Insert(0, $Marker)
    # UTF-8 without a byte-order mark: the server's config reader cannot parse a first line that starts with one.
    [IO.File]::WriteAllLines($file, [string[]]$lines, (New-Object Text.UTF8Encoding($false)))
    Write-Host ("{0,-28} {1} settings applied" -f (Split-Path $file -Leaf), $all.Count)
}

